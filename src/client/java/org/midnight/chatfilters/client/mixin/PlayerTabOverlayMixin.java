package org.midnight.chatfilters.client.mixin;

import net.minecraft.client.gui.components.PlayerTabOverlay;
import net.minecraft.client.multiplayer.PlayerInfo;
import net.minecraft.network.chat.Component;
import org.midnight.chatfilters.client.filter.ChatFilter;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(PlayerTabOverlay.class)
public class PlayerTabOverlayMixin {
	@Inject(method = "getNameForDisplay", at = @At("RETURN"), cancellable = true)
	private void chatfilters$tabName(PlayerInfo info, CallbackInfoReturnable<Component> cir) {
		cir.setReturnValue(ChatFilter.applyCached(cir.getReturnValue(), ChatFilter.Origin.TAB_LIST));
	}
}